-- kb2 대목 이름 중복 차단 (2026-09-16)
-- ════════════════════════════════════════════════════════════════════════════
-- 자동 그룹화(kb2_taxonomy.auto_group_ungrouped_documents)가 제안받은 대목마다
-- create_group 을 무조건 불러서, **버튼을 누를 때마다 같은 이름의 대목이 하나씩 늘었다.**
-- 실측(2026-09-16): 활성 대목 6개가 9/9 세대에서 만들어진 채 남아 있었고, 그 상태에서
-- 버튼을 한 번 더 누르면 12개가 된다 — 세무사 화면에서 같은 주제가 두 줄로 갈라진다.
--
-- 코드는 이미 두 겹으로 막는다(모델에 기존 레이블을 후보로 주고, get_or_create_group 이
-- 정규화 비교로 재사용). 이 인덱스는 그 **바깥의 경로**를 막는 자리다 — 화면의
-- [대목 추가] 버튼(POST /api/kb2/groups)은 create_group 을 직접 부르고, 두 세무사가
-- 동시에 같은 이름을 넣으면 코드 검사만으로는 둘 다 통과한다.
--
-- ── 왜 정규화 인덱스인가 ────────────────────────────────────────────────────
-- 모델이 '차량·자산 관련비'와 '차량 자산 관련비'를 회차마다 오간다. label 그대로
-- unique 를 걸면 그 둘이 서로 다른 값이라 중복이 그대로 통과한다. 그래서
-- kb2_store.norm_label 과 **같은 규칙**(공백 제거 · 가운뎃점 제거 · 소문자)으로 건다.
--
-- ── 왜 부분 인덱스(status='active')인가 ─────────────────────────────────────
-- ① 지금 DB에 이름이 겹치는 deleted 대목이 실제로 있다('브라우저검증용 대목' 2건,
--    브라우저 검증 잔여물) — 전체에 걸면 이 마이그레이션 자체가 실패한다.
-- ② 사람이 지운 대목을 이름이 같다는 이유로 되살리지 않는다는 get_or_create_group 의
--    결정과 같은 선이다. 지운 뒤 같은 이름으로 다시 만드는 것은 막을 이유가 없다.
-- ════════════════════════════════════════════════════════════════════════════

create unique index if not exists kb2_groups_active_label_norm_uniq
  on kb2.groups (lower(replace(regexp_replace(label, '\s', '', 'g'), '·', '')))
  where status = 'active';

comment on index kb2.kb2_groups_active_label_norm_uniq is
  '활성 대목 이름 중복 차단 — 공백·가운뎃점·대소문자를 무시한 비교(kb2_store.norm_label 과 동일 규칙).';
