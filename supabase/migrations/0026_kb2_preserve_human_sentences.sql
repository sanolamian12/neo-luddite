-- 0026 — 세대교체 축적성(G2): 사람이 손댄 문장을 보존하고 의미로 재부착한다.
--
-- 문제(2026-09-12 실물 관측): 재구조화는 archive_all_active_documents() 로 활성 세대를
-- 통째로 내린다. 그래서 세무사가 '기타'에서 빼내 진짜 세목에 넣은 문장 fc17e2f6 이
-- **한 회차 만에 원상복귀**했다 — 옮긴 문장은 archived 문서 안에서 검색 밖으로 나갔고,
-- 같은 원문은 새 세대에서 새 문장으로 다시 '기타'에 담겼다. KB2 의 논지는 "KB 는
-- 세무사 코멘트로 자란다"인데 실제로는 자라지 않고 회차마다 다시 만들어지고 있었다.
--
-- 결정: **보존 + 의미 기반 재부착.** 사람이 손댄 문장은 archive 하지 않고 새 세대 목차 중
-- 레이블 임베딩이 가장 가까운 세목에 다시 붙인다. 맞는 자리가 없으면 '기타'로 내린다.
--
-- 왜 문자열 매칭이 아니라 임베딩인가 — 측정된 사실이다. 목차 레이블은 세대를 넘어
-- 33~67% 만 남는다(최근 4회 67/33/47/60%). 하필 fc17e2f6 의 목적지 '1세대1주택비과세'
-- 가 이번에 사라진 12개 중 하나였다. 그런데 **의미는 남는다**: 세대 N→N+1 최근접 쌍
-- 171건을 전부 찍어보니 1세대1주택비과세→양도소득세비과세(0.7399),
-- 감가상각→감가상각비(0.8795), 부가가치세→부가가치세신고(0.8174) 처럼 이어진다.
-- 임계값 0.70 은 그 목록에서 오탐이 시작되는 지점(0.6303 개인차량비용인정→접대비인정,
-- '인정' 접미사에 걸린 것) 위에 여유를 두고 그었다 — 0.70 이상은 전수 정탐이다.
--
-- 이 마이그레이션은 이력 제약만 넓힌다. 보존 대상 판정은 런타임 쿼리로 한다
-- (kb2_store.list_human_touched_sentences) — 사람이 손댄 흔적은 이미
-- sentence_versions.editor_type 에 전부 남아 있어서 별도 플래그를 둘 이유가 없고,
-- 플래그를 두면 이력과 플래그가 어긋날 자리가 하나 더 생긴다.
alter table kb2.sentence_versions
  drop constraint sentence_versions_editor_type_check,
  add constraint sentence_versions_editor_type_check
    check (editor_type in (
      'system_synthesis', 'system_unsorted', 'auditor_edit', 'admin_revert',
      'moved', 'retired', 'reconnected', 'regenerated_reattach'
    ));

-- 소급 보정은 따로 하지 않는다. 보존 대상 쿼리가 **문서 상태를 보지 않기** 때문에,
-- 지금 archived 문서 안에 갇혀 있는 3건(c6e40c44 auditor_edit / fc17e2f6 moved /
-- acdb99cb retired+reconnected)은 다음 재구조화에서 자동으로 딸려 올라온다. 이건
-- 편의적 예외가 아니라 정의 그대로다 — "사람이 손댄 문장은 어디에 있든 새 세대로
-- 따라온다". 지금 고치는 게 싼 이유이기도 하다(해당 문장이 아직 3건뿐이다).
